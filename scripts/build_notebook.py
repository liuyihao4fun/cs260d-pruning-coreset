"""Regenerate notebooks/colab_run.ipynb with the current src/ embedded in it.

    python scripts/build_notebook.py

The notebook writes every src/*.py file onto the Colab machine with %%writefile,
so Colab never has to clone the private repo (no GitHub token needed).
Run this after ANY change under src/, then commit both src/ and the notebook.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
cells = []


def md(s):
    cells.append({"cell_type": "markdown", "metadata": {}, "source": s.strip("\n").splitlines(True)})


def code(s, collapsed=False):
    meta = {"cellView": "form"} if collapsed else {}
    cells.append({"cell_type": "code", "metadata": meta, "execution_count": None, "outputs": [],
                  "source": s.strip("\n").splitlines(True)})


md("""
# CS 260D — Coreset fine-tuning after pruning (Colab launcher)

Run the cells top to bottom. **Runtime → Change runtime type → T4 GPU** first.

This notebook is generated by `scripts/build_notebook.py` and contains a copy of `src/`
(section 2), so no GitHub token is needed. Do not edit code here: edit `src/` in the repo,
re-run `python scripts/build_notebook.py`, push, and re-open the notebook from GitHub.
""")
code("!nvidia-smi --query-gpu=name,memory.total --format=csv")
md("## 1. Mount Google Drive (checkpoints + results survive disconnects)")
code("""
from google.colab import drive
drive.mount('/content/drive')

WORK = '/content/drive/MyDrive/cs260d'        # shared folder for checkpoint + results
CKPT = f'{WORK}/resnet18_cifar10.pt'
DATA = f'{WORK}/data'                         # CIFAR cached on Drive: downloaded once, reused by later sessions
NAME = 'me'                                   # <-- change to your name so teammates' results don't collide
RESULTS = f'{WORK}/results_{NAME}.jsonl'
import os; os.makedirs(WORK, exist_ok=True)
""")
md("## 2. Write the code onto this machine")
files = sorted(p for p in (ROOT / "src").rglob("*.py"))
dirs = sorted({str(p.parent.relative_to(ROOT)) for p in files})
code("import os\n" + "".join(f"os.makedirs('/content/repo/{d}', exist_ok=True)\n" for d in dirs)
     + "%cd /content/repo")
for p in files:
    rel = p.relative_to(ROOT)
    code(f"%%writefile /content/repo/{rel}\n" + p.read_text(), collapsed=True)
md("## 3. Train the dense model (once — skipped if the checkpoint already exists)\n\n"
   "~40 epochs, roughly 20 min on a T4. Only ONE teammate needs to do this; share the Drive folder.")
code("""
import os
if not os.path.exists(CKPT):
    !python -m src.train_dense --dataset cifar10 --epochs 40 --data_root "{DATA}" --out "{CKPT}"
else:
    print('checkpoint exists:', CKPT)
""")
md("## 4. Smoke test: one run (90% sparsity, CRAIG, 10% data, 5 epochs)")
code("""
!python -m src.finetune --ckpt "{CKPT}" --data_root "{DATA}" --sparsity 0.9 --method craig \\
    --frac 0.1 --epochs 5 --results /content/smoke.jsonl
""")
md("""
## 5. Main grid

Resumable: if Colab disconnects, re-run sections 1–2 and this cell; finished runs are skipped.

Split work across teammates with `SHARD` = 0 / 1 / 2 and `NUM_SHARDS` = 3.
""")
code("""
SHARD, NUM_SHARDS = 0, 1
!python -m src.run_grid --ckpt "{CKPT}" --data_root "{DATA}" --results "{RESULTS}" \\
    --sparsities 0.9 0.95 0.98 --methods full random craig el2n damage_topk damage_fl \\
    --fracs 0.05 0.1 0.2 --seeds 0 1 2 --epochs 30 \\
    --shard {SHARD} --num_shards {NUM_SHARDS}
""")
md("""
## 6. Extra: re-select the subset every 5 epochs

Same 30-epoch budget, but the subset is re-chosen with the current model every 5 epochs.
Random is re-drawn too, so all three methods see the same amount of distinct data.
Keys get an `_rs5` suffix, so these never collide with the one-shot runs above.
""")
code("""
!python -m src.run_grid --ckpt "{CKPT}" --data_root "{DATA}" --results "{RESULTS}" \\
    --sparsities 0.9 0.95 0.98 --methods random craig damage_fl \\
    --fracs 0.05 0.1 0.2 --seeds 0 1 2 --epochs 30 --reselect_every 5
""")
md("""
## 7. Diagnostic: how skewed are CRAIG weights when re-selecting?

Re-selected CRAIG / damage_fl runs sometimes collapse right after a re-selection. Each run now
prints `weights: {...}` at every selection: max weight / mean weight, the share of total weight
held by the top 1% of selected samples, and the model's training accuracy before selecting.
Four cases: two that collapsed, one stable control (5% data), one 98%-sparsity case.
Results go to a separate file so the main results are untouched.
""")
code("""
for sp, m, fr, sd in [(0.9, "craig", 0.2, 2), (0.9, "craig", 0.05, 0), (0.9, "damage_fl", 0.2, 0), (0.98, "craig", 0.2, 0)]:
    !python -m src.finetune --ckpt "{CKPT}" --data_root "{DATA}" --results "{WORK}/results_diag.jsonl" --sparsity {sp} --method {m} --frac {fr} --seed {sd} --epochs 30 --reselect_every 5 --tag diag
""")
md("## 8. Plot (reads every teammate's results file in the Drive folder)")
code("""
!python -m src.plot --results {WORK}/results_*.jsonl --out {WORK}/figures
from IPython.display import Image
Image(f'{WORK}/figures/acc_vs_frac.png')
""")

nb = {"cells": cells,
      "metadata": {"accelerator": "GPU", "colab": {"provenance": [], "gpuType": "T4"},
                   "kernelspec": {"name": "python3", "display_name": "Python 3"},
                   "language_info": {"name": "python"}},
      "nbformat": 4, "nbformat_minor": 0}
out = ROOT / "notebooks" / "colab_run.ipynb"
out.write_text(json.dumps(nb, indent=1))
print(f"wrote {out} with {len(files)} embedded source files")
