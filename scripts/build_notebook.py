NAME = 'me'                                   # <-- change to your name so teammates' results don't collide
RESULTS = f'{WORK}/results_audit_{NAME}.jsonl'
import os; os.makedirs(WORK, exist_ok=True)
""")
md("## 2. Write the code onto this machine")
files = sorted(p for p in (ROOT / "src").rglob("*.py"))
dirs = sorted({str(p.parent.relative_to(ROOT)) for p in files})
code("import os\n" + "".join(f"os.makedirs('/content/cs260d-pruning-coreset/{d}', exist_ok=True)\n" for d in dirs)
     + "%cd /content/cs260d-pruning-coreset")
for p in files:
    rel = p.relative_to(ROOT)
    code(f"%%writefile /content/cs260d-pruning-coreset/{rel}\n" + p.read_text(), collapsed=True)
md("## 3. Require the existing dense checkpoint (never train it automatically)")
code("""
import os
assert os.path.isfile(CKPT), f'Ask your teammate for the existing checkpoint: {CKPT}'
from src.audit import file_sha256
print('checkpoint:', CKPT, 'SHA256:', file_sha256(CKPT))
""")
md("## 4. Smoke test: one run (90% sparsity, CRAIG, 10% data, 5 epochs)")
code("""
