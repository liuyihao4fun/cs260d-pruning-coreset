for cell in cells:
    text = ''.join(cell['source'])
    if (cell['cell_type'] == 'code' and not text.startswith('%%writefile ')
            and ('src.run_grid' in text or 'for sp, m, fr, sd in' in text)):
        if 'RUN_LARGE_GRIDS = False' in text:
            text = text.replace('RUN_LARGE_GRIDS = False  # explicitly opt in; do not run all historical experiments for phase 1\n', '')
        cell['source'] = ("if globals().get('RUN_LARGE_GRIDS', False):\n" +
                          ''.join('    ' + line for line in text.splitlines(True)) +
                          "\nelse:\n    print('Skipped historical grid; see COLAB_RUN_GUIDE.md for small audit runs.')\n").splitlines(True)

nb = {"cells": cells,
      "metadata": {"accelerator": "GPU", "colab": {"provenance": [], "gpuType": "T4"},
                   "kernelspec": {"name": "python3", "display_name": "Python 3"},
                   "language_info": {"name": "python"}},
      "nbformat": 4, "nbformat_minor": 0}
def main():
    p = argparse.ArgumentParser()
    p.add_argument('--check', action='store_true', help='verify without writing')
    p.add_argument('--out', type=pathlib.Path, default=ROOT / 'notebooks' / 'colab_run.ipynb')
    a = p.parse_args()
    rendered = json.dumps(nb, indent=1)
    if a.check:
        if not a.out.exists() or a.out.read_text() != rendered:
            raise SystemExit('Notebook is stale; run python scripts/build_notebook.py')
        print('Notebook matches all embedded sources and launcher cells')
    else:
        a.out.write_text(rendered)
        print(f'wrote {a.out} with {len(files)} embedded source files')


if __name__ == '__main__':
    main()
